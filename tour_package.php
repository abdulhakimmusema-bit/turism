        <h3>A beautiful, lesser-known gem in Ethiopia's Central Region (Siltʼe Zone) for local tourism, offering swimming, boating, fish soup (Koroso), and proximity to waterfalls and hot springs.</h3>
        
        <p>Silte Abaya Lake is a serene spot for nature lovers, offering relaxation and a taste of local culture near Siltʼe communities. It is distinct from the larger, famous Lake Abaya in the Rift Valley, which is known for crocodiles and reddish-brown water.</p>
        
        <h4 class="subsection-title">Key Details</h4>
        <p>The lake is located in the Silti Zone, between the East Silti, Silti, and Lanfuro districts. It is approximately 42 km northeast of Worabe town and 152 km from Addis Ababa. The lake covers an area of over 1,154 hectares (about 11.54 km²) and has an average depth of up to 9 meters. The lake and its surroundings support a diverse ecosystem, including around 112 animal species and over 50 types of aquatic flora. While their numbers have declined, hippos can still be found in the area. The region is also home to a variety of bird species.</p>
        
